
def area(a):
    '''
    Принимает сторону квадрата, возвращает площадь этого квадрата, т.е. квадрат стороны
    
    Пример вызова:
    >>> area(2)
    <<< 4
    '''
    return a ** 2


def perimeter(a):
    '''
    Принимает сторону квадрата, возвращает периметр этого квадрата, т.е. сумму четырех одинаковых сторон
    
    Пример вызова:
    >>> perimeter(2)
    <<< 8
    '''
    return 4 * a
